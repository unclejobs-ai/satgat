import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');
const CONSTRAINT_PATH = path.join(REPO_ROOT, 'src/lib/design-system/constraint.ts');
const OUTPUT_PATH = path.join(REPO_ROOT, 'app/satgat-tokens.css');

const TOKEN_SPECS = [
  ['CANVAS', 'canvas', 'color'],
  ['IVORY', 'surface', 'color'],
  ['CANVAS_DARK', 'surface-muted', 'color'],
  ['INK', 'ink', 'color'],
  ['INK_LIGHT', 'ink-body', 'color'],
  ['INK_MUTED', 'ink-muted', 'color'],
  ['HAIRLINE', 'line', 'color'],
  ['BORDER', 'line-strong', 'color'],
  ['MUTED', 'text-subtle', 'color'],
  ['PLACEHOLDER', 'placeholder', 'color'],
  ['DANCHEONG', 'accent', 'color'],
  ['DANCHEONG_LIGHT', 'accent-hover', 'color'],
  ['JADE', 'jade', 'color'],
  ['JADE_LIGHT', 'jade-hover', 'color'],
  ['GOLD', 'gold', 'color'],
  ['GOLD_LIGHT', 'gold-soft', 'color'],
  ['FONT_MYEONGJO', 'font-display', 'font'],
  ['FONT_BATANG', 'font-body', 'font'],
  ['FONT_DODUM', 'font-label', 'font'],
];

const REQUIRED_EXPORTS = new Set([
  'CANVAS',
  'IVORY',
  'INK',
  'INK_LIGHT',
  'INK_MUTED',
  'HAIRLINE',
  'DANCHEONG',
  'FONT_MYEONGJO',
  'FONT_BATANG',
  'FONT_DODUM',
]);

function isExported(node) {
  return node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword) ?? false;
}

export async function readConstraintValues(filePath = CONSTRAINT_PATH) {
  const source = await fs.readFile(filePath, 'utf8');
  const sourceFile = ts.createSourceFile(filePath, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  if (sourceFile.parseDiagnostics.length > 0) {
    throw new Error('constraint.ts must be valid TypeScript');
  }
  const wanted = new Set(TOKEN_SPECS.map(([name]) => name));
  const values = {};

  for (const statement of sourceFile.statements) {
    if (!ts.isVariableStatement(statement) || !isExported(statement)) continue;
    if ((statement.declarationList.flags & ts.NodeFlags.Const) === 0) {
      throw new Error('Constraint tokens must use export const declarations');
    }
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || !wanted.has(declaration.name.text)) continue;
      if (!declaration.initializer || !ts.isStringLiteral(declaration.initializer)) {
        throw new Error(`${declaration.name.text} must be a string literal in constraint.ts`);
      }
      if (Object.hasOwn(values, declaration.name.text)) {
        throw new Error(`Duplicate constraint export: ${declaration.name.text}`);
      }
      values[declaration.name.text] = declaration.initializer.text;
    }
  }

  for (const name of REQUIRED_EXPORTS) {
    if (!Object.hasOwn(values, name)) throw new Error(`Missing constraint export: ${name}`);
  }
  return values;
}

function normalizeColor(name, value) {
  if (!/^#[0-9A-Fa-f]{6}$/.test(value)) {
    throw new Error(`${name} must be a six-digit solid hex color`);
  }
  return value.toUpperCase();
}

export function renderTokenCss(values) {
  const rows = [];
  for (const [exportName, cssName, kind] of TOKEN_SPECS) {
    if (!Object.hasOwn(values, exportName)) continue;
    const value = kind === 'color' ? normalizeColor(exportName, values[exportName]) : values[exportName];
    if (kind === 'font' && (typeof value !== 'string' || value.trim() === '')) {
      throw new Error(`${exportName} must be a non-empty font stack`);
    }
    rows.push(`  --satgat-${cssName}: ${value};`);
  }

  for (const name of REQUIRED_EXPORTS) {
    if (!Object.hasOwn(values, name)) throw new Error(`Missing token value: ${name}`);
  }

  return [
    '/* Generated by scripts/generate-design-tokens.mjs. Do not edit by hand. */',
    ':root {',
    ...rows,
    '}',
    '',
  ].join('\n');
}

async function writeAtomically(filePath, content) {
  const temporaryPath = `${filePath}.${process.pid}.tmp`;
  await fs.writeFile(temporaryPath, content, 'utf8');
  await fs.rename(temporaryPath, filePath);
}

export function parseArgs(argv) {
  if (argv.length !== 1 || !['--write', '--check'].includes(argv[0])) {
    throw new Error('Usage: node scripts/generate-design-tokens.mjs --write|--check');
  }
  return argv[0];
}

export async function run(argv = process.argv.slice(2)) {
  const command = parseArgs(argv);
  const expected = renderTokenCss(await readConstraintValues());
  if (command === '--write') {
    await writeAtomically(OUTPUT_PATH, expected);
    return;
  }

  let actual;
  try {
    actual = await fs.readFile(OUTPUT_PATH, 'utf8');
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
      throw new Error('app/satgat-tokens.css is missing; run the generator with --write');
    }
    throw error;
  }
  if (actual !== expected) {
    throw new Error('app/satgat-tokens.css is stale; run the generator with --write');
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  run().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
